"""2단계: 내 카카오톡으로 테스트 메시지를 보낸다.

이 단계의 목적은 딱 하나다.
"나와의 채팅"에 메시지가 도착하면서 휴대폰 푸시 알림이 울리는지 확인하는 것.
알림이 울리면 계획대로 진행하고, 안 울리면 다른 방식으로 바꾼다.

버튼과 링크는 아직 넣지 않는다. 카카오는 메시지에 들어가는 링크의 도메인을
앱에 미리 등록하도록 요구하는데, 카드뉴스 주소가 아직 없기 때문이다.
1단계에서 GitHub Pages 주소가 생기면 그때 등록하고 버튼을 붙인다.
"""

import kakaolib

TEMPLATE = {
    "object_type": "text",
    "text": (
        "[모닝 리포트] 발송 테스트\n\n"
        "① 유가 +6.1%, 나스닥 -1.2%, 반도체 -1.9%\n"
        "② 하이닉스 HBM4 계약 호재 vs 하락장\n"
        "③ 밤 9시 30분 미국 CPI 발표\n\n"
        "위 숫자는 예시입니다.\n"
        "이 메시지가 알림과 함께 도착했다면 0단계 성공."
    ),
    "link": {},
}


def main():
    env = kakaolib.load_env()
    kakaolib.send_to_me(env, TEMPLATE)

    print("발송 요청이 성공했습니다.")
    print()
    print("이제 휴대폰을 확인하세요.")
    print("  1. 카카오톡 알림이 울렸나요?")
    print("  2. '나와의 채팅'에 메시지가 있나요?")
    print()
    print("둘 다 되면 0단계 통과입니다.")


if __name__ == "__main__":
    main()
